local CHAT = {}
function DEFAULT_CHAT_FRAME:AddMessage(msg) CHAT[#CHAT + 1] = tostring(msg) end
local checks, boxes, drops = {}, {}, {}
local origCreateFrame = CreateFrame
function CreateFrame(kind, name, parent, template)
	local f = origCreateFrame(kind, name, parent, template)
	if template == "UICheckButtonTemplate" then checks[#checks + 1] = f end
	if template == "InputBoxTemplate" then boxes[#boxes + 1] = f end
	if template == "WowStyle1DropdownTemplate" then drops[#drops + 1] = f end
	return f
end

-- saved: left 3000 pixels (more than half the window width), without monitor data
qnCoreCharDB = { layout = "account:Raid" }
qnViewPortDB = { profiles = { ["account:Raid"] = { viewport = { 3000, 0, 0, 0 }, dual = { useMonitorData = false } } }, global = {} }

LoadAddon("qnCore")
local vp = LoadAddon("qnViewPort")
local L = vp.L
FireEvent("PLAYER_LOGIN")
FireEvent("PLAYER_ENTERING_WORLD", true, false)
RunTimers()
SetEditModeLayout(3)

-- left offset of WorldFrame in screen pixels
local function WFLeft()
	local ux = vp.UnitsPerPixel()
	return math.floor(WorldFrame._points[1][2] / ux + 0.5)
end
local function Count(key)
	local n = 0
	for _, m in ipairs(CHAT) do if m:find(L[key], 1, true) then n = n + 1 end end
	return n
end
-- checkbox whose check mark follows vp.db.dual[key] on refresh (also via getter)
local function CheckBox(key)
	local d = vp.db.dual
	local old, found = d[key], nil
	for _, cb in ipairs(checks) do
		if not found and rawget(cb, "Refresh") then
			d[key] = true cb:Refresh() local on = cb._checked
			d[key] = false cb:Refresh() local off = cb._checked
			if on == true and not off then found = cb end
		end
	end
	d[key] = old
	if found then found:Refresh() end
	return found
end
local function Click(cb, on)
	cb:SetChecked(on)
	cb:GetScript("OnClick")(cb)
	RunTimers()
end

-- 1. load: apply clamped, keep the saved value
Check(vp.db.viewport[1] == 3000, "load: saved value stays 3000: " .. vp.db.viewport[1])
Check(vp.GetViewport()[1] == 2880 and WFLeft() == 2880, "load: applied clamped to 2880: " .. WFLeft())

-- 2. window size: apply clamped, do not save
winW, winH = 4000, 2000
FireEvent("DISPLAY_SIZE_CHANGED") RunTimers()
Check(vp.GetViewport()[1] == 2000 and vp.db.viewport[1] == 3000, "smaller window: 2000 applied, 3000 saved")
winW, winH = 5760, 2160
FireEvent("DISPLAY_SIZE_CHANGED") RunTimers()
Check(vp.GetViewport()[1] == 2880 and vp.db.viewport[1] == 3000, "window large again: 2880 applied, 3000 saved")

-- 3. Blizzard resets WorldFrame: the applied value is restored
WorldFrame._points = {}
WorldFrame:SetAllPoints()
Check(WorldFrame._points[1] and WFLeft() == 2880, "hook on WorldFrame restores the clamped viewport")

-- 4. profile switch: new profile = copy, applied clamped, nothing saved
SetEditModeLayout(4)
Check(vp.db ~= qnViewPortDB.profiles["account:Raid"] and vp.db.viewport[1] == 3000 and vp.GetViewport()[1] == 2880,
	"profile switch: copy keeps 3000, applied 2880")
SetEditModeLayout(3)

-- 5. player input saves; without confirmation the previously saved value is written back
SlashCmdList.QNVIEWPORT("100 0 0 0")
Check(vp.db.viewport[1] == 100 and WFLeft() == 100, "/qnvp 100 0 0 0 saves and applies")
T = T + 21
RunTickers()
Check(vp.db.viewport[1] == 3000 and vp.GetViewport()[1] == 2880 and Count("Setting not confirmed – previous viewport restored.") == 1,
	"after 20 s without confirmation: saved value 3000 restored unchanged")
SlashCmdList.QNVIEWPORT("0 0 0 0")
Check(vp.db.viewport[1] == 0 and not vp.IsActive(), "/qnvp 0 0 0 0 saves immediately")

-- 6. mapFade: on remembers the value, off writes it back
local cFade = CheckBox("mapNoFade")
Check(cFade ~= nil, "checkbox mapNoFade found")
C_CVar._v.mapFade = "1"
Click(cFade, true)
Check(C_CVar._v.mapFade == "0" and qnViewPortDB.global.mapFadeSaved == "1", "mapNoFade on: mapFade 0, previous 1 remembered account-wide")
FireEvent("PLAYER_ENTERING_WORLD", false, false) RunTimers()
Check(C_CVar._v.mapFade == "0" and qnViewPortDB.global.mapFadeSaved == "1", "loading screen: stays 0, remembered value stays")
Click(cFade, false)
Check(C_CVar._v.mapFade == "1" and qnViewPortDB.global.mapFadeSaved == nil, "mapNoFade off: 1 restored")
C_CVar._v.mapFade = "0"   -- set by the player in Blizzard's options
FireEvent("PLAYER_ENTERING_WORLD", false, false) RunTimers()
Check(C_CVar._v.mapFade == "0", "mapNoFade off: CVar is not touched otherwise")
Click(cFade, true)
Click(cFade, false)
Check(C_CVar._v.mapFade == "1", "without remembered value: Blizzard's default when switching off")

