-- 11. refresh the "Second monitor" options page: manual values or measured, locked values
local function Box(key) for _, b in ipairs(boxes) do if b.key == key then return b end end end
local function Record(w)
	rawset(w, "SetEnabled", function(self, on) self._enabled = on end)
	if rawget(w, "label") then
		rawset(w.label, "SetFontObject", function(self, font) self._font = font end)
	end
end
for _, b in ipairs(boxes) do Record(b) end
local side
for _, dd in ipairs(drops) do
	Record(dd)
	for _, r in ipairs(dd._radios or {}) do
		if r.text == L["Left of the main monitor"] then side = dd end
	end
end
local wBox, hBox, yBox = Box("width"), Box("height"), Box("offsetY")
Check(wBox and hBox and yBox and side, "fields and side selection found")
vp.db.dual.width, vp.db.dual.height, vp.db.dual.offsetY, vp.db.dual.side = 1600, 1000, 50, "RIGHT"
vp.db.dual.mapFollowZone = true
vp.Dual.RefreshOptions()
Check(wBox._text == 1600 and hBox._text == 1000 and yBox._text == 50, ("without monitor data: manual values %s/%s/%s"):format(
	tostring(wBox._text), tostring(hBox._text), tostring(yBox._text)))
Check(wBox._enabled == true and wBox.label._font == "GameFontHighlight", "without monitor data: field usable")
Check(side._enabled == true and side.label._font == "GameFontHighlight" and side._text == L["Right of the main monitor"],
	"without monitor data: side usable: " .. tostring(side._text))
Check(CheckBox("mapFollowZone")._checked == true and not CheckBox("mapNoFade")._checked, ("checkboxes from DB: %s/%s"):format(
	tostring(CheckBox("mapFollowZone")._checked), tostring(CheckBox("mapNoFade")._checked)))
local bx = Box("bagsOffsetX")
vp.db.dual.bagsOffsetX = 12
vp.Dual.RefreshOptions()
Check(bx and bx._text == 12 and bx._enabled == nil, "bag offset: value, not locked")
vp.db.dual.useMonitorData = true
vp.Dual.RefreshOptions()
Check(wBox._text == 1920 and hBox._text == 1200 and yBox._text == 377, ("monitor data: measured values %s/%s/%s"):format(
	tostring(wBox._text), tostring(hBox._text), tostring(yBox._text)))
Check(wBox._enabled == false and yBox.label._font == "GameFontDisable", "monitor data: fields locked")
Check(side._enabled == false and side.label._font == "GameFontDisable", "monitor data: side locked")
Check(vp.db.dual.width == 1600, "monitor data: manual value stays saved")
vp.db.dual.useMonitorData = false
vp.Dual.RefreshOptions()
Check(wBox._text == 1600 and wBox._enabled == true, "without monitor data again: manual value")

